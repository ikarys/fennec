//! `docs/map.md`: the project map as Markdown, a Mermaid diagram and a table,
//! for whoever arrives on the project (a developer, an agent). Regenerated,
//! never edited by hand: a file that differs from a fresh render is stale.

use serde::Serialize;

use super::module_map::ModuleMap;

pub const MAP_FILE: &str = "docs/map.md";

/// The committed map against a fresh render.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum MapFileState {
    Missing,
    Stale,
    Current,
}

pub fn state(on_disk: Option<&str>, rendered: &str) -> MapFileState {
    match on_disk {
        None => MapFileState::Missing,
        Some(text) if text == rendered => MapFileState::Current,
        Some(_) => MapFileState::Stale,
    }
}

pub fn render(map: &ModuleMap) -> String {
    if map.modules.is_empty() {
        return "# Project map\n\nNo source files found.\n".to_string();
    }
    let mut out = String::new();
    out.push_str("# Project map\n\n");
    out.push_str("Generated by fennec from the import lines of the source files: do not edit, regenerate it.\n");
    out.push_str("Each box is a module (a directory); an arrow `A --> B` means code in A imports code in B, labelled with the number of importing files.\n\n");
    out.push_str("```mermaid\ngraph LR\n");
    for (index, module) in map.modules.iter().enumerate() {
        let label = module.id.replace('"', "#quot;");
        out.push_str(&format!("  m{index}[\"{label}\"]\n"));
    }
    for dependency in &map.dependencies {
        let imports = dependency.imports;
        if let Some(from) = map.modules.iter().position(|m| m.id == dependency.from)
            && let Some(to) = map.modules.iter().position(|m| m.id == dependency.to)
        {
            out.push_str(&format!("  m{from} -->|{imports}| m{to}\n"));
        }
    }
    out.push_str("```\n\n");
    out.push_str("| Module | Files | Tests | Entry point | What it is |\n|---|---|---|---|---|\n");
    for module in &map.modules {
        let entry = if module.entry { "yes" } else { "" };
        // The authors' own words, from the head file's doc comment; a `|` would end the cell.
        let what = module.summary.as_deref().unwrap_or("").replace('|', "\\|");
        out.push_str(&format!(
            "| `{}` | {} | {} | {entry} | {what} |\n",
            module.id, module.files, module.tests
        ));
    }
    out
}

#[cfg(test)]
mod tests {
    use super::render;
    use crate::domain::module_map::{Dependency, Module, ModuleMap};

    fn module(id: &str, files: usize, tests: usize, entry: bool) -> Module {
        Module {
            id: id.into(),
            group: String::new(),
            files,
            tests,
            entry,
            ..Default::default()
        }
    }

    #[test]
    fn renders_two_module_map() {
        let map = ModuleMap {
            modules: vec![
                module("crates/fennec/src", 14, 12, true),
                module("crates/fennec/src/domain", 29, 27, false),
            ],
            dependencies: vec![Dependency {
                from: "crates/fennec/src".into(),
                to: "crates/fennec/src/domain".into(),
                imports: 12,
                ..Default::default()
            }],
            groups: vec![],
        };
        assert_eq!(
            render(&map),
            r#"# Project map

Generated by fennec from the import lines of the source files: do not edit, regenerate it.
Each box is a module (a directory); an arrow `A --> B` means code in A imports code in B, labelled with the number of importing files.

```mermaid
graph LR
  m0["crates/fennec/src"]
  m1["crates/fennec/src/domain"]
  m0 -->|12| m1
```

| Module | Files | Tests | Entry point | What it is |
|---|---|---|---|---|
| `crates/fennec/src` | 14 | 12 | yes |  |
| `crates/fennec/src/domain` | 29 | 27 |  |  |
"#
        );
    }

    #[test]
    fn renders_empty_map() {
        let map = ModuleMap {
            modules: vec![],
            dependencies: vec![],
            groups: vec![],
        };
        assert_eq!(render(&map), "# Project map\n\nNo source files found.\n");
    }

    #[test]
    fn skips_unknown_dependency() {
        let map = ModuleMap {
            modules: vec![module("a", 1, 0, false)],
            dependencies: vec![Dependency {
                from: "a".into(),
                to: "missing".into(),
                imports: 3,
                ..Default::default()
            }],
            groups: vec![],
        };
        assert_eq!(
            render(&map),
            r#"# Project map

Generated by fennec from the import lines of the source files: do not edit, regenerate it.
Each box is a module (a directory); an arrow `A --> B` means code in A imports code in B, labelled with the number of importing files.

```mermaid
graph LR
  m0["a"]
```

| Module | Files | Tests | Entry point | What it is |
|---|---|---|---|---|
| `a` | 1 | 0 |  |  |
"#
        );
    }
}
